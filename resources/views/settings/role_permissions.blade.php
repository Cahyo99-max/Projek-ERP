                $(document).on('change', '.perm-toggle', function() {
                    let cardId = $(this).data('card');
                    let card   = $('#' + cardId);
                    if ($(this).is(':checked')) {
                        card.removeClass('perm-card-inactive').addClass('perm-card-active');
                    } else {
                        card.removeClass('perm-card-active').addClass('perm-card-inactive');
                    }
                    updateCheckedCounter();
                });

                // Event handler 3: Pilih Semua (Visible only)
                $(document).on('click', '#btnCheckAll', function() {
                    $('.perm-card-wrapper:visible .perm-toggle').each(function() {
                        if (!$(this).is(':checked')) {
                            $(this).prop('checked', true).trigger('change');
                        }
                    });
                });

                // Event handler 4: Kosongkan (Visible only)
                $(document).on('click', '#btnUncheckAll', function() {
                    $('.perm-card-wrapper:visible .perm-toggle').each(function() {
                        if ($(this).is(':checked')) {
                            $(this).prop('checked', false).trigger('change');
                        }
                    });
                });

                // Event handler 5: Live search filtering dengan debounce untuk responsivitas maksimal
                let searchDebounce = null;
                $(document).on('input', '#searchPermissionInput', function() {
                    clearTimeout(searchDebounce);
                    let q = $(this).val().toLowerCase().trim();

                    searchDebounce = setTimeout(function() {
                        if (!q) {
                            $('.perm-card-wrapper').show();
                            $('.perm-subgroup-block').show();
                            $('.perm-module-block').show();
                            return;
                        }

                        $('.perm-card-wrapper').each(function() {
                            let label = $(this).find('.perm-card-label').text().toLowerCase();
                            let val   = $(this).find('.perm-toggle').val().toLowerCase();
                            if (label.includes(q) || val.includes(q)) {
                                $(this).show();
                            } else {
                                $(this).hide();
                            }
                        });

                        // Toggle sub-groups visibility
                        $('.perm-subgroup-block').each(function() {
                            let hasVisible = $(this).find('.perm-card-wrapper:visible').length > 0;
                            $(this).toggle(hasVisible);
                        });

                        // Toggle modules visibility
                        $('.perm-module-block').each(function() {
                            let hasVisible = $(this).find('.perm-card-wrapper:visible').length > 0;
                            $(this).toggle(hasVisible);
                        });
                    }, 120);
                });

                // Event handler 6: Simpan Form Akses
                $('#formUpdateAkses').on('submit', function(e) {
                    e.preventDefault();
                    let roleId   = $('#edit_role_id').val();
                    let formData = $(this).serialize();
                    let btn      = $('#btnSimpanAkses');
                    btn.html('<span class="spinner-border spinner-border-sm me-2"></span> Menyimpan...').prop('disabled', true);

                    $.ajax({
                        url: '/roles/' + roleId + '/permissions/update',
                        type: 'POST',
                        data: formData,
                        success: function(res) {
                            $('#modalAkses').modal('hide');
                            Swal.fire({
                                title: 'Berhasil!',
                                text: res.message,
                                icon: 'success',
                                timer: 1500,
                                showConfirmButton: false
                            }).then(() => location.reload());
                        },
                        error: function(err) {
                            btn.html('<i class="bi bi-save me-2"></i> Simpan Perubahan').prop('disabled', false);
                            let msg = err.responseJSON?.message ?? 'Terjadi kesalahan saat menyimpan.';
                            Swal.fire('Gagal!', msg, 'error');
                        }
                    });
                });
            });
