                                                <i class="bi bi-caret-right-fill text-${module.color}"></i> ${subTitle}
                                            </div>
                                            <div class="row g-2">`;

                                    perms.forEach(function(perm) {
                                        let isChecked  = rolePerms.includes(perm.name) ? 'checked' : '';
                                        let labelName  = permissionTranslations[perm.name] || perm.name.replace(/-/g, ' ').replace(/\b\w/g, l => l.toUpperCase());
                                        let activeBorder = `border: 1.5px solid var(--bs-${module.color}, #0d6efd) !important; background-color: rgba(var(--bs-${module.color}-rgb, 13, 110, 253), 0.1);`;
                                        let inactiveBorder = `border: 1px solid var(--bs-border-color, rgba(128,128,128,0.25)) !important; background-color: var(--bs-card-bg, var(--bs-body-bg));`;

                                        html += `
                                            <div class="col-12 col-sm-6">
                                                <div class="card perm-card shadow-xs" 
                                                     style="border-radius:12px; ${isChecked ? activeBorder : inactiveBorder} transition: all 0.2s;"
                                                     id="card_${perm.id}">
                                                    <div class="card-body py-2 px-3 d-flex justify-content-between align-items-center">
                                                        <label for="perm_${perm.id}" class="mb-0 fw-medium perm-card-label text-body-emphasis pe-2" style="cursor:pointer; font-size: 0.88rem;">
                                                            ${labelName}
                                                        </label>
                                                        <div class="form-check form-switch mb-0 ms-2">
                                                            <input class="form-check-input perm-toggle" type="checkbox" role="switch"
                                                                id="perm_${perm.id}" name="permissions[]" value="${perm.name}" ${isChecked}
                                                                style="width:2.8em;height:1.4em;cursor:pointer;"
                                                                data-card="card_${perm.id}"
                                                                data-color="${module.color}">
                                                        </div>
                                                    </div>
                                                </div>
                                            </div>`;
                                    });

                                    html += `</div></div>`;
                                });
                            }

                            html += `</div>`;
                        });

                        $('#permissionsContainer').html(html);

                        // Trigger animation state on check toggle
                        $(document).on('change', '.perm-toggle', function() {
                            let cardId = $(this).data('card');
                            let color  = $(this).data('color');
                            let card   = $('#' + cardId);
                            if ($(this).is(':checked')) {
                                card.attr('style', `border-radius:12px; border: 1.5px solid var(--bs-${color}, #0d6efd) !important; background-color: rgba(var(--bs-${color}-rgb, 13, 110, 253), 0.1); transition: all 0.2s;`);
                            } else {
                                card.attr('style', `border-radius:12px; border: 1px solid var(--bs-border-color, rgba(128,128,128,0.25)) !important; background-color: var(--bs-card-bg, var(--bs-body-bg)); transition: all 0.2s;`);
                            }
                        });

                    }).fail(function() {
                        $('#permissionsContainer').html('<div class="alert alert-danger m-3">Gagal mengambil data akses.</div>');
                    });
                });

                $('#formUpdateAkses').on('submit', function(e) {
                    e.preventDefault();
                    let roleId   = $('#edit_role_id').val();
                    let formData = $(this).serialize();
                    let btn      = $('#btnSimpanAkses');
                    btn.html('<span class="spinner-border spinner-border-sm me-2"></span> Menyimpan...').prop('disabled', true);

                    $.ajax({
                        url: '/roles/' + roleId + '/permissions/update',
                        type: 'POST',
                        data: formData,
                        success: function(res) {
                            $('#modalAkses').modal('hide');
                            Swal.fire({
                                title: 'Berhasil!',
                                text: res.message,
                                icon: 'success',
                                timer: 1500,
                                showConfirmButton: false
                            }).then(() => location.reload());
                        },
                        error: function(err) {
                            btn.html('<i class="bi bi-save me-2"></i> Simpan Perubahan').prop('disabled', false);
                            let msg = err.responseJSON?.message ?? 'Terjadi kesalahan saat menyimpan.';
                            Swal.fire('Gagal!', msg, 'error');
                        }
                    });
                });
            });
